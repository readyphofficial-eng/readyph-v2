function buildHtml(title: string, heading: string, childName: string, exercises: string[]): string {
  return `
    <html><head><title>${title}</title>
    <style>
      body { font-family: 'Comic Sans MS', sans-serif; padding: 30px; max-width: 700px; margin: auto; }
      h1 { text-align: center; color: #f97316; }
      .name { font-size: 18px; margin: 20px 0; border-bottom: 2px dashed #ccc; padding-bottom: 10px; }
      .item { margin: 12px 0; font-size: 15px; }
      .blank { display: inline-block; border-bottom: 2px solid #333; width: 100px; margin: 0 5px; }
      .footer { margin-top: 40px; text-align: center; color: #999; font-size: 12px; }
      @media print { .item { page-break-inside: avoid; } }
    </style></head><body>
    <h1>Ready PH Worksheet</h1>
    <div class="name">Name: <b>${childName || '_____'}</b> &nbsp;&nbsp; Date: ${new Date().toLocaleDateString()}</div>
    <h2>Subject: ${heading}</h2>
    ${exercises.map((ex, i) => `<div class="item">${i + 1}. ${ex}</div>`).join('')}
    <div class="footer">Ready PH - Ready Kinder, Ready Elementary, Ready Highschool</div>
    </body></html>
  `;
}

