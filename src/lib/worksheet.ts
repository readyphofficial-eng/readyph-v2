import type { VideoCategory } from '@/types';
import type { ElementarySubject } from '@/lib/elementaryQuestions';

export function generateWorksheet(category: VideoCategory, childName: string): void {
  const w = window.open('', '_blank');
  if (!w) return;
  const title = `Ready PH Worksheet - ${category}`;
  const exercises = getPreschoolExercises(category);
  w.document.write(buildHtml(title, category, childName, exercises));
  w.document.close();
  setTimeout(() => w.print(), 500);
}

